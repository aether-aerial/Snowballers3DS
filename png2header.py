"""
png2header.py - convert a PNG sprite into a C header for the 3DS (RGB565).

Usage:   python png2header.py penguin.png source/penguin.h penguin
Needs:   pip install pillow

How it works:
  1. Crop the image to the visible pixels.
  2. Convert each pixel from 24-bit RGB to 16-bit RGB565
     (5 bits red, 6 bits green, 5 bits blue), the format the top screen uses.
  3. Mark transparent pixels with a "key" color (magenta, 0xF81F) that the
     game skips when drawing.
  4. Write it out as a const array so it's compiled straight into the .3dsx.
"""
import sys
from PIL import Image

KEY = 0xF81F  # magenta = transparent


def to_rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)
    src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
    up = name.upper()

    im = Image.open(src).convert("RGBA")
    im = im.crop(im.getbbox())
    w, h = im.size
    px = im.load()

    vals = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a < 128:
                vals.append(KEY)
            else:
                v = to_rgb565(r, g, b)
                vals.append(0xF81E if v == KEY else v)  # don't clash with the key

    with open(dst, "w") as f:
        f.write(f"// Generated by png2header.py from {src} (RGB565, 0x{KEY:04X} = transparent)\n")
        f.write("#pragma once\n")
        f.write(f"#define {up}_W {w}\n#define {up}_H {h}\n#define {up}_KEY 0x{KEY:04X}\n")
        f.write(f"static const u16 {name}_px[{up}_W * {up}_H] = {{\n")
        for i in range(0, len(vals), 16):
            f.write("    " + ", ".join(f"0x{v:04X}" for v in vals[i:i + 16]) + ",\n")
        f.write("};\n")
    print(f"wrote {dst}: {w}x{h}")


if __name__ == "__main__":
    main()
